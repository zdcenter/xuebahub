const fs = require('fs');
const path = require('path');

const now = new Date();
const pad = (n) => String(n).padStart(2, '0');

const year = now.getFullYear();
const month = pad(now.getMonth() + 1);
const day = pad(now.getDate());
const hours = pad(now.getHours());
const minutes = pad(now.getMinutes());

// 自动生成按年月日与时间编号，如: 20261021.1500
const buildId = `${year}${month}${day}.${hours}${minutes}`;
const buildTime = `${year}-${month}-${day} ${hours}:${minutes}`;
const version = 'v1.3.4';
const fullText = `${version} · ${buildId}`;

// 自动从 public/xuebaw-collector.user.js 读取唯一真实版本号，保证全后台同步
let collectorVersion = 'v1.5.1';
const collectorPath = path.join(__dirname, '../public/xuebaw-collector.user.js');
if (fs.existsSync(collectorPath)) {
  const collectorSrc = fs.readFileSync(collectorPath, 'utf-8');
  const m = collectorSrc.match(/@version\s+([^\s]+)/);
  if (m && m[1]) {
    collectorVersion = m[1].startsWith('v') ? m[1] : `v${m[1]}`;
  }
}

const content = `// This file is auto-generated by scripts/generate-version.js on each build. Do not edit manually.
export const APP_VERSION = {
  version: '${version}',
  buildId: '${buildId}',
  buildTime: '${buildTime}',
  fullText: '${fullText}'
};

export const COLLECTOR_VERSION = '${collectorVersion}';
`;

const targetDir = path.join(__dirname, '../src/app');
if (!fs.existsSync(targetDir)) {
  fs.mkdirSync(targetDir, { recursive: true });
}

const targetFile = path.join(targetDir, 'version.ts');
fs.writeFileSync(targetFile, content, 'utf-8');
console.log(`[Version Generator] Generated APP_VERSION: ${fullText}`);
